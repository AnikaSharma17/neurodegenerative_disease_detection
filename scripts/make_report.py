"""Aggregate runs/ into results/RESULTS.md and copy representative figures.

Groups runs by configuration (everything except the seed) and reports mean ± std
over seeds. Bootstrap CIs (patient-resampled) are averaged over seeds.

    python scripts/make_report.py
"""
from __future__ import annotations

import argparse
import json
import shutil
from collections import defaultdict
from pathlib import Path

import numpy as np


def ms(values) -> str:
    v = np.array([x for x in values if x is not None and not np.isnan(x)], dtype=float)
    if len(v) == 0:
        return "–"
    return f"{v.mean():.3f} ± {v.std(ddof=1):.3f}" if len(v) > 1 else f"{v.mean():.3f}"


def config_key(r: dict) -> tuple:
    return (r["arch"], r["backbone"], r["seg_weight"], r["split_level"])


def label(key: tuple) -> str:
    arch, backbone, seg, split = key
    return f"{arch} / {backbone} / seg {seg:g} / {split}-level split"


def load_runs(root: Path, disease: str) -> dict[tuple, list[dict]]:
    groups = defaultdict(list)
    for f in sorted((root / disease).glob("*/test_metrics.json")):
        r = json.loads(f.read_text())
        if r.get("cv_folds") or r.get("arch") == "mil":
            continue  # cross-validation runs are summarised by scripts/run_cv.py
        r["_dir"] = f.parent
        groups[config_key(r)].append(r)
    return groups


def col(rs: list[dict], *path: str) -> str:
    vals = []
    for r in rs:
        for key in path:
            r = r[key]
        vals.append(r)
    return ms(vals)


def table(groups: dict[tuple, list[dict]], baselines: list[dict], baseline_tag: str) -> list[str]:
    lines = ["| Model | Seeds | Slice balanced acc. | Slice macro-F1 | 95% CI macro-F1 (patient bootstrap) "
             "| Patient-level acc. | ECE before → after T-scaling | Best epoch |",
             "|---|---|---|---|---|---|---|---|"]
    by_model = defaultdict(list)
    for b in baselines:
        by_model[b["model"]].append(b)
    for model, rs in by_model.items():
        ci = np.mean([r["test_ci95"]["macro_f1"] for r in rs], axis=0)
        lines.append(f"| baseline: {model} ({baseline_tag}) | {len(rs)} | {col(rs, 'test', 'balanced_accuracy')} | "
                     f"{col(rs, 'test', 'macro_f1')} | {ci[0]:.2f}–{ci[1]:.2f} | "
                     f"{col(rs, 'test_patient_level', 'accuracy')} | – | – |")
    for key, rs in sorted(groups.items(), key=lambda kv: (kv[0][3] != "group", kv[0])):
        ci = np.mean([r["test_ci95"]["macro_f1"] for r in rs if r.get("test_ci95")], axis=0)
        patient = col(rs, "test_patient_level", "accuracy") if key[3] == "group" else "n/a"
        ece = f"{col(rs, 'calibration', 'ece_before')} → {col(rs, 'calibration', 'ece_after')}"
        epochs = ", ".join(str(r.get("best_epoch", "?")) for r in rs)
        lines.append(f"| {label(key)} | {len(rs)} | {col(rs, 'test', 'balanced_accuracy')} | "
                     f"{col(rs, 'test', 'macro_f1')} | {ci[0]:.2f}–{ci[1]:.2f} | {patient} | {ece} | {epochs} |")
    return lines


def per_class(rs: list[dict]) -> list[str]:
    classes = list(rs[0]["test"]["per_class"])
    lines = ["| Class | Recall (mean ± std) | Precision | Test slices (seed 0) |", "|---|---|---|---|"]
    for c in classes:
        rec = [r["test"]["per_class"][c]["recall"] for r in rs]
        prec = [r["test"]["per_class"][c]["precision"] for r in rs]
        lines.append(f"| {c} | {ms(rec)} | {ms(prec)} | {rs[0]['test']['per_class'][c]['support']} |")
    return lines


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--runs", default="runs")
    p.add_argument("--out", default="results")
    p.add_argument("--main-config", default="multitask,efficientnet_b0,1,group")
    args = p.parse_args()
    runs, out = Path(args.runs), Path(args.out)
    arch, backbone, seg, split = args.main_config.split(",")
    main_key = (arch, backbone, float(seg), split)

    md = ["# Results", "",
          "Generated by `python scripts/make_report.py` from `runs/`. Mean ± std over seeds 0, 1, 2.",
          "Group-level splits keep every patient (Alzheimer) or MRI series (Parkinson) in a single split.",
          "Image-level rows reproduce the original leaky protocol, for comparison only.", ""]
    for disease in ("alzheimer", "parkinson"):
        groups = load_runs(runs, disease)
        if not groups:
            continue
        md += [f"## {disease.capitalize()}", ""]
        for tag in ("group", "image"):
            bfile = runs / disease / f"baselines_{tag}.json"
            baselines = json.loads(bfile.read_text()) if bfile.exists() else []
            sub = {k: v for k, v in groups.items() if k[3] == tag}
            if sub or baselines:
                md += [f"### {tag.capitalize()}-level split", "", *table(sub, baselines, tag), ""]
        if main_key in groups:
            rs = groups[main_key]
            md += [f"### Per-class, {label(main_key)}", "", *per_class(rs), ""]
            cams = [json.loads((r["_dir"] / "gradcam_summary.json").read_text())["cam_mass_inside_head_mean"]
                    for r in rs if (r["_dir"] / "gradcam_summary.json").exists()]
            if cams:
                md += [f"Grad-CAM: fraction of attention inside the head mask = {ms(cams)} "
                       f"(over {len(cams)} seeds; low values mean the model looks at background "
                       "or scanner artefacts).", ""]
            best = max(rs, key=lambda r: r["test"]["macro_f1"])
            dest = out / disease
            dest.mkdir(parents=True, exist_ok=True)
            for f in ("confusion_matrix.png", "curves.png", "calibration.png", "gradcam_gallery.png",
                      "test_metrics.json", "gradcam_summary.json"):
                if (best["_dir"] / f).exists():
                    shutil.copy(best["_dir"] / f, dest / f)
            md += [f"Figures in `results/{disease}/` are from seed {best['seed']} (highest test macro-F1 of the "
                   "three, so slightly optimistic).", ""]
    (out / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
